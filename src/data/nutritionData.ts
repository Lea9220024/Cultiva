export function getNutrientById(id: string): Nutrient | undefined {
  return NUTRIENTS.find((n) => n.id === id);
}

export function getNaturalSourceById(id: string): NaturalSource | undefined {
  return NATURAL_SOURCES.find((s) => s.id === id);
}

export function getMineralSourceById(id: string): MineralSource | undefined {
  return MINERAL_SOURCES.find((m) => m.id === id);
}

export function getGenericFertilizerById(id: string): GenericFertilizer | undefined {
  return GENERIC_FERTILIZERS.find((f) => f.id === id);
}

export function getContextInfo(id: string): ContextInfoItem | undefined {
  if (CONTEXT_INFO_MAP[id]) return CONTEXT_INFO_MAP[id];

  // Fallback to searching in nutrients
  const nut = getNutrientById(id);
  if (nut) {
    return {
      id: nut.id,
      name: nut.name,
      category: "nutriente",
      icon: "🌱",
      badge: nut.category === "macronutriente_primario" ? "Macronutriente Primario" : "Micronutriente",
      whatIs: nut.shortDescription,
      purpose: nut.whatItDoes,
      whereToFind: nut.commonSources.join(", "),
      usageContext: "Relevante en etapas: " + nut.relevantStages.join(", "),
      precautions: nut.excessConsiderations,
      sources: nut.sources,
    };
  }

  // Fallback to natural sources
  const nat = getNaturalSourceById(id);
  if (nat) {
    return {
      id: nat.id,
      name: nat.name,
      category: "fuente_natural",
      icon: "🌿",
      badge: "Enmienda Natural",
      whatIs: nat.description,
      purpose: "Aporta: " + nat.nutrientsProvided.join(", "),
      whereToFind: nat.whereToFindIt,
      usageContext: nat.applicationContext,
      precautions: nat.warnings,
      sources: nat.sources,
    };
  }

  return undefined;
}