export function getRecommendedDoseForWeek(
  system: string,
  weekNumber: number
): { product: FertilizerProduct; doseMlPerL: number; frequency?: string }[] {
  const schedule = TOP_CROP_SCHEDULES[system] || TOP_CROP_SCHEDULES.Tierra;
  const week = schedule.weeks.find((w) => w.weekNumber === weekNumber) || schedule.weeks[0];

  return week.dosages
    .map((d) => {
      const product = TOP_CROP_PRODUCTS.find((p) => p.id === d.productId);
      if (!product) return null;
      return {
        product,
        doseMlPerL: d.doseMlPerL,
        frequency: d.frequency,
      };
    })
    .filter(Boolean) as { product: FertilizerProduct; doseMlPerL: number; frequency?: string }[];
}

export function checkProductCombinationConflict(productIds: string[]): {
  hasConflict: boolean;
  conflictWarnings: string[];
} {
  if (productIds.length <= 1) {
    return { hasConflict: false, conflictWarnings: [] };
  }

  const warnings: string[] = [];

  // Conflict 1: Mixing Top Coco with Top Veg or Top Bloom (Tierra and Coco shouldn't be mixed simultaneously)
  const hasCocoBase = productIds.some((id) => id === "top_coco_a" || id === "top_coco_b");
  const hasTierraBase = productIds.some(
    (id) => id === "top_veg" || id === "top_bloom" || id === "top_auto"
  );
  if (hasCocoBase && hasTierraBase) {
    warnings.push(
      "⚠️ Esta combinación no está documentada en la tabla seleccionada. Verificá la compatibilidad y las instrucciones de las etiquetas antes de utilizarla (mezcla de bases orgánicas para tierra con bases minerales de coco)."
    );
  }

  // Conflict 2: Top Wash with any base fertilizer
  const hasWash = productIds.includes("top_wash");
  const hasAnyNutrient = productIds.some((id) => id !== "top_wash");
  if (hasWash && hasAnyNutrient) {
    warnings.push(
      "⚠️ Top Wash debe aplicarse exclusivamente solo con agua para permitir la evacuación de sales minerales acumuladas. No mezclar con otros abonos."
    );
  }

  // Conflict 3: Big One + Top Bud in same irrigation (redundant high PK/stimulant)
  if (productIds.includes("big_one") && productIds.includes("top_bud")) {
    warnings.push(
      "⚠️ Big One está destinado al inicio/transición de floración y Top Bud a la fase de engorde tardía. Aplicarlos juntos en un mismo riego puede elevar excesivamente la electroconductividad (EC)."
    );
  }

  return {
    hasConflict: warnings.length > 0,
    conflictWarnings: warnings,
  };
}
